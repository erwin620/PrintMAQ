/* Fallo fatal del RTOS: detiene todo y deja D2 y D3 encendidos fijos (activos en bajo),
   lo que distingue este fallo del parpadeo normal de estado. */
static void Rtos_Fatal(void)
{
  taskDISABLE_INTERRUPTS();
  HAL_GPIO_WritePin(LED_D2_PORT, LED_D2_PIN | LED_D3_PIN, GPIO_PIN_RESET);
  for (;;)
  {
  }
}

void vApplicationStackOverflowHook(TaskHandle_t xTask, char *pcTaskName)
{
  (void)xTask;
  (void)pcTaskName;
  Rtos_Fatal();
}

void vApplicationMallocFailedHook(void)
{
  Rtos_Fatal();
}

